import test from "node:test";
import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { recoveryHarness } from "./fixtures/agent-recovery-harness.mjs";

test("three source tasks run in one Codex chat and persist exactly one verified writeback per task", async t => {
  const f = await recoveryHarness(t);
  await f.create();
  await f.finish();
  await f.assertExactlyOnce();
  const proofs = f.packets.filter(packet => packet.action === "events").flatMap(packet => packet.input.events).filter(event => event.type === "verification.completed");
  assert.equal(new Set(proofs.map(event => event.turnId)).size, 3);
  assert.ok(proofs.every(event => event.payload.results.every(result => result.status === "passed" && /^[a-f0-9]{64}$/.test(result.outputHash))));
});

test("human acceptance survives Runner restart and only the exact confirmation writes once before the next turn", async t => {
  const f = await recoveryHarness(t);
  f.items[0].acceptance = [{ id: "human-review", kind: "human", required: true, description: "Review the first artifact" }];
  await f.create();
  await f.until(async () => (await f.view()).queue.phase === "waiting_human");
  const waiting = await f.view();
  const proof = (await f.storage.get(`exec:queue-proof:${f.runId}:${waiting.turnId}:verification.completed`));
  assert.equal(proof.payload.results[0].status, "needs_input");
  assert.equal((await f.storage.list({ prefix: "fixture:done:" })).size, 0);
  await f.restart();
  await f.until(async () => (await f.view()).queue.phase === "waiting_human");
  const resumed = await f.view();
  assert.equal(resumed.threadId, waiting.threadId);
  assert.equal(resumed.turnId, waiting.turnId);
  assert.equal((await f.nativeState()).calls.filter(call => call.method === "turn/start").length, 1);
  assert.deepEqual(await f.storage.get(`exec:queue-proof:${f.runId}:${waiting.turnId}:verification.completed`), proof);
  await assert.rejects(f.control("confirm", { expectedTurnId: "wrong-turn" }), { code: "EXECUTION_HTTP_409" });
  await assert.rejects(f.control("confirm", { expectedTurnId: waiting.turnId, expectedRevision: resumed.queue.revision + 1 }), { code: "EXECUTION_HTTP_409" });
  assert.equal((await f.storage.list({ prefix: "fixture:done:" })).size, 0);
  const confirmation = { requestId: "confirm-original-turn", expectedTurnId: waiting.turnId, expectedRevision: resumed.queue.revision };
  const receipt = await f.control("confirm", confirmation);
  assert.deepEqual(await f.control("confirm", confirmation), receipt);
  await f.finish();
  await f.assertExactlyOnce();
  const calls = (await f.storage.get("fixture:finalize-calls")).filter(call => call.source.taskRef.taskId === "task-1");
  assert.equal(calls.length, 1);
  assert.equal(calls[0].completedTurnId, waiting.turnId);
  assert.equal((await f.nativeState()).calls.filter(call => call.method === "turn/start")[1].params.threadId, waiting.threadId);
});

test("failed file acceptance exhausts one repair, stops publicly, then a new run verifies the fixed file without replacing old proof", async t => {
  const f = await recoveryHarness(t, { mode: "batch-background" });
  f.items.splice(1);
  f.items[0].acceptance[0].predicate = { type: "textContains", text: "accepted-output" };
  const first = await f.create({ requestId: "failed-file-run" });
  const oldRunId = f.runId;
  await f.until(async () => {
    const view = await f.view();
    const proofs = [...(await f.storage.list({ prefix: `exec:queue-proof:${oldRunId}:` })).values()].filter(event => event.type === "verification.completed");
    return view.queue.phase === "blocked" && view.queue.repairCount === 1 && proofs.length === 2;
  });
  const oldRun = f.runs.getRun(oldRunId);
  const oldProofs = [...(await f.storage.list({ prefix: `exec:queue-proof:${oldRunId}:` })).values()].filter(event => event.type === "verification.completed");
  assert.equal(oldProofs.length, 2);
  assert.equal(new Set(oldProofs.map(proof => proof.turnId)).size, 2);
  assert.ok(oldProofs.every(proof => proof.runId === oldRunId && proof.threadId === oldRun.threadId && proof.payload.results[0].status === "failed" && proof.payload.results[0].failureKind === "predicate"));
  assert.equal((await f.storage.list({ prefix: "fixture:done:" })).size, 0);
  assert.equal((await f.nativeState()).threads[0].terminals.length, 2);
  for (let n = 0; n < 3; n++) await f.tick();
  assert.equal((await f.nativeState()).calls.filter(call => call.method === "turn/start").length, 2);
  await f.dispatch.tool(f.principal, "codex_cancel_run", { runId: oldRunId, requestId: "stop-failed-file-run" });
  await f.until(() => !f.executor.hasHold);
  const stopped = await f.view();
  assert.equal(stopped.status, "cancelled");
  assert.equal(stopped.terminal && stopped.stopConfirmed, true);
  assert.equal(f.controller.store.leases().length, 0);
  assert.equal(await f.storage.get(`fixture:lease:${oldRunId}`), undefined);
  assert.equal(await f.storage.get("exec:queue-workspace:" + f.workspaceId), undefined);
  assert.deepEqual((await f.nativeState()).threads[0].terminals, []);
  assert.equal((await f.nativeState()).calls.filter(call => call.method === "thread/backgroundTerminals/terminate").length, 2);
  assert.equal((await f.storage.list({ prefix: "fixture:done:" })).size, 0);
  await writeFile(path.join(f.workspace, "1.txt"), "accepted-output\n");
  const second = await f.create({ requestId: "fixed-file-new-run" });
  assert.notEqual(f.runId, oldRunId);
  assert.notEqual(second.commandId, first.commandId);
  await f.finish();
  const completed = await f.view();
  assert.notEqual(completed.threadId, oldRun.threadId);
  assert.equal(completed.batch.items[0].writeback.status, "applied");
  const newProof = await f.storage.get(`exec:queue-proof:${f.runId}:${completed.turnId}:verification.completed`);
  assert.equal(newProof.runId, f.runId);
  assert.equal(newProof.threadId, completed.threadId);
  assert.equal(newProof.payload.results[0].status, "passed");
  assert.notEqual(newProof.payload.results[0].outputHash, oldProofs[1].payload.results[0].outputHash);
  assert.deepEqual([...(await f.storage.list({ prefix: `exec:queue-proof:${oldRunId}:` })).values()].filter(event => event.type === "verification.completed"), oldProofs);
  assert.equal((await f.storage.get("exec:run:" + oldRunId)).view.status, "cancelled");
  const native = await f.nativeState();
  assert.equal(native.calls.filter(call => call.method === "thread/start").length, 2);
  assert.equal(native.calls.filter(call => call.method === "turn/start").length, 3);
  assert.deepEqual(await f.storage.get("fixture:done:task-1"), { runId: f.runId, turnId: completed.turnId, effects: 1 });
});
